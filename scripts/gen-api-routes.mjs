#!/usr/bin/env node
// Extracts the control-plane REST route table from the Go sources and keeps the
// generated index in site/src/content/docs/docs/reference/api.mdx complete.
//   node scripts/gen-api-routes.mjs          print the routes ("METHOD /path", sorted)
//   node scripts/gen-api-routes.mjs --write  rewrite the generated block in api.mdx
//   node scripts/gen-api-routes.mjs --check  exit 1 if api.mdx is missing a route (or lists a removed one)
// Deterministic: no network, no Go toolchain, only a regex over the registration calls.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'services/control-plane');
const DOC = path.join(root, 'site/src/content/docs/docs/reference/api.mdx');
const START = '{/* routes:start (generated by scripts/gen-api-routes.mjs; do not edit) */}';
const END = '{/* routes:end */}';
// Fixture servers that live under cmd/ but are not the control-plane API.
const SKIP_DIRS = new Set(['connector-replay', 'llm-replay']);

function* goFiles(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) yield* goFiles(p); }
    else if (e.name.endsWith('.go') && !e.name.endsWith('_test.go')) yield p;
  }
}

export function extractRoutes() {
  const re = /\.(?:HandleFunc|Handle)\(\s*"([A-Z]+) (\/[^"\s]*)"/g;
  const out = new Set();
  for (const sub of ['cmd', 'internal']) {
    for (const f of goFiles(path.join(SRC, sub))) {
      for (const m of fs.readFileSync(f, 'utf8').matchAll(re)) out.add(`${m[1]} ${m[2]}`);
    }
  }
  return [...out].sort((a, b) => {
    const [ma, pa] = a.split(' '), [mb, pb] = b.split(' ');
    return pa === pb ? ma.localeCompare(mb) : pa.localeCompare(pb);
  });
}

function block(routes) {
  return `${START}\n\`\`\`text\n${routes.join('\n')}\n\`\`\`\n${END}`;
}

function docRoutes(text) {
  const m = text.match(/\{\/\* routes:start[^]*?\*\/\}\n```text\n([^]*?)\n```\n\{\/\* routes:end \*\/\}/);
  return m ? m[1].split('\n').filter(Boolean) : null;
}

const mode = process.argv[2];
const routes = extractRoutes();
if (!mode) { console.log(routes.join('\n')); process.exit(0); }
const text = fs.readFileSync(DOC, 'utf8');
if (mode === '--write') {
  const re = /\{\/\* routes:start[^]*?\{\/\* routes:end \*\/\}/;
  if (!re.test(text)) { console.error('api.mdx has no routes:start/end block'); process.exit(1); }
  fs.writeFileSync(DOC, text.replace(re, () => block(routes)));
  console.log(`wrote ${routes.length} routes`);
} else if (mode === '--check') {
  const have = docRoutes(text);
  if (!have) { console.error('api.mdx has no generated routes block; run: node scripts/gen-api-routes.mjs --write'); process.exit(1); }
  const missing = routes.filter((r) => !have.includes(r));
  const stale = have.filter((r) => !routes.includes(r));
  if (missing.length || stale.length) {
    for (const r of missing) console.error(`missing from api.mdx: ${r}`);
    for (const r of stale) console.error(`in api.mdx but not in the code: ${r}`);
    console.error('run: node scripts/gen-api-routes.mjs --write  (then document any new area in prose above the index)');
    process.exit(1);
  }
  console.log(`api.mdx lists all ${routes.length} routes`);
} else { console.error('usage: gen-api-routes.mjs [--write|--check]'); process.exit(2); }
