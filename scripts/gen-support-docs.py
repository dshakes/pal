#!/usr/bin/env python3
"""Regenerate services/control-plane/internal/handlers/support_docs.go from the
docs frontmatter (ADR 0059). TestSupportDocsMatchSite fails until this is re-run
after a docs page is added, renamed or re-described."""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
docs = root / "site/src/content/docs/docs"
out = root / "services/control-plane/internal/handlers/support_docs.go"


def front(text: str, key: str) -> str:
    for line in text.splitlines():
        if line.startswith(key + ":"):
            v = line[len(key) + 1:].strip()
            return v[1:-1] if len(v) >= 2 and v[0] == v[-1] == '"' else v
    return ""


rows = []
for f in sorted(docs.rglob("*.mdx")):
    slug = f.relative_to(docs).with_suffix("").as_posix()
    if slug == "index":
        slug = ""
    elif slug.endswith("/index"):
        slug = slug[: -len("/index")]
    text = f.read_text()
    rows.append((slug, front(text, "title"), front(text, "description")))

lines = [
    "package handlers",
    "",
    "// support_docs.go — the PAL docs index the support agent grounds in. One entry",
    "// per page under site/src/content/docs/docs; title and summary are the page's",
    "// own frontmatter. Generated by scripts/gen-support-docs.py; TestSupportDocsMatchSite",
    "// fails when it drifts.",
    "",
    "type supportDoc struct {",
    '\tSlug    string `json:"slug"`',
    '\tTitle   string `json:"title"`',
    '\tSummary string `json:"summary"`',
    "}",
    "",
    "var supportDocs = []supportDoc{",
]
for slug, title, desc in sorted(rows):
    lines.append(f"\t{{Slug: {json.dumps(slug)}, Title: {json.dumps(title)}, Summary: {json.dumps(desc)}}},")
lines.append("}")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {len(rows)} docs to {out.relative_to(root)}")
